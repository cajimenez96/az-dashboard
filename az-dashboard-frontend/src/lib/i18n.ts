export function clientStatusLabel(status: ClientStatus): string {
  switch (status) {
    case "ACTIVE":
      return t.clients.statusActive;
    case "INACTIVE":
      return t.clients.statusInactive;
    case "AT_RISK":
      return t.clients.statusAtRisk;
    default:
      return status;
  }
}

export function taskPriorityLabel(priority: TaskPriority): string {
  switch (priority) {
    case "LOW":
      return t.tasks.form.priorityLow;
    case "MEDIUM":
      return t.tasks.form.priorityMedium;
    case "HIGH":
      return t.tasks.form.priorityHigh;
    case "URGENT":
      return t.tasks.form.priorityUrgent;
    default:
      return priority;
  }
}
